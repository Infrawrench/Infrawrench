/**
 * `infraenv <command>`: parse, dispatch, and turn failures into exit codes.
 * Each command module is a dynamic import, so the bundle splits per command
 * and `--version`, `--help` and the hook commands load nothing they do not run.
 */
import { parseCommandLine, type CommandName, type ParsedArgs } from "./args";
import { Exit, Failure, UsageError, type Io } from "./io";
import { VERSION } from "./version";

const USAGE = `infraenv ${VERSION}: keep .env in step with a committed .infraenv

Usage: infraenv <command> [flags]

Commands:
  pull        Resolve .infraenv through Infrawrench and write .env
  check       What every reference in .infraenv points at, and what is broken
  install     Git hooks that pull again when a commit changes .infraenv
  uninstall   Remove the hooks (or the block, from a hook someone else wrote)
  status      Whether each hook is installed
  login       Store an API key for this machine
  logout      Forget the stored API key
  whoami      The key in use and its organization
  skill       Where the bundled agent skill is; \`skill install\` links it for agents

Flags:
  -h, --help       Help for a command (infraenv pull --help)
  -v, --version    Print the version
      --no-color   No ANSI colours

Credentials: INFRAWRENCH_API_KEY, else the key \`infraenv login\` stored. Without
either, pull and check run \`infrawrench env\` from the desktop app when it is
installed. Docs: https://infrawrench.com/docs/features/env-files
`;

