async function dispatch(io: Io, args: ParsedArgs, command: CommandName): Promise<number> {
  switch (command) {
    case "pull":
      return (await import("./commands/pull")).pull(io, args);
    case "check":
      return (await import("./commands/check")).check(io, args);
    case "install":
      return (await import("./commands/hooks")).install(io, args);
    case "uninstall":
      return (await import("./commands/hooks")).uninstall(io, args);
    case "status":
      return (await import("./commands/hooks")).status(io, args);
    case "login":
      return (await import("./commands/auth")).login(io, args);
    case "logout":
      return (await import("./commands/auth")).logout(io);
    case "whoami":
      return (await import("./commands/auth")).whoami(io, args);
    case "skill":
      return (await import("./commands/skill")).skill(io, args);
    case "help": {
      const topic = args.rest[0];
      if (topic === undefined) {
        io.out(USAGE);
        return 0;
      }
      if (!Object.hasOwn(HELP, topic))
        throw new UsageError(`Unknown command ${JSON.stringify(topic)}`);
      io.out(HELP[topic as CommandName]);
      return 0;
    }
  }
}

/** Run one command line; resolves with the exit code. Never throws. */
export async function run(
  argv: readonly string[],
  makeIo: (noColor: boolean) => Io,
): Promise<number> {
  let args: ParsedArgs;
  try {
    args = parseCommandLine(argv);
  } catch (error) {
    const io = makeIo(true);
    io.err(`infraenv: ${error instanceof Error ? error.message : String(error)}\n`);
    io.err("Run `infraenv --help` for usage.\n");
    return 2;
  }
  const io = makeIo(args.noColor);
  if (args.version) {
    io.out(`${VERSION}\n`);
    return 0;
  }
  if (args.command === null) {
    io.out(USAGE);
    return args.help ? 0 : 2;
  }
  if (args.help) {
    io.out(HELP[args.command]);
    return 0;
  }
  try {
    return await dispatch(io, args, args.command);
  } catch (error) {
    if (error instanceof Exit) return error.exitCode;
    if (error instanceof Failure) {
      io.err(`infraenv: ${error.message}\n`);
      if (error instanceof UsageError) io.err("Run `infraenv --help` for usage.\n");
      return error.exitCode;
    }
    io.err(
      `infraenv: ${error instanceof Error ? (error.stack ?? error.message) : String(error)}\n`,
    );
    return 1;
  }
}
