/**
 * For the few surfaces holding a type id but no type definition: plugin-declared
 * pseudo-resources (`DashboardCardSchema`) have ids that are often a word from
 * the vocabulary already, as in `firestore-index`. Reads last word first, because
 * the noun comes last: a `database-user` is a user.
 */
export function inferIconKey(resourceTypeId: string | undefined): string | undefined {
  return resourceTypeId
    ?.split("-")
    .reverse()
    .find((word) => word in RESOURCE_ICON_KEYS);
}

export interface ResourceTypeIconProps {
  iconKey?: string | undefined;
  className?: string | undefined;
  size?: number | string | undefined;
  /** Thinner strokes for an icon drawn large. */
  strokeWidth?: number | undefined;
}

export function ResourceTypeIcon({
  iconKey,
  className,
  size = 24,
  strokeWidth = 2,
}: ResourceTypeIconProps) {
  // `box` for a type with no key, which is what a resource is when all we know
  // about it is that it is a resource.
  const name = (iconKey && RESOURCE_ICON_KEYS[iconKey]) || "box";
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      {NODES[name].map(([tag, attrs], index) => createElement(tag, { key: index, ...attrs }))}
    </svg>
  );
}
