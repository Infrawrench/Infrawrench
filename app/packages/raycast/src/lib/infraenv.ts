import { chmod, mkdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import path from "node:path";
import {
  INFRAENV_FILE_NAME,
  fetchInfraenvDescribe,
  fetchInfraenvResolve,
  infraenvOutputPath,
  infraenvPullDecision,
  parseInfraenv,
  type InfraenvDescribeResponse,
  type InfraenvResolveResponse,
} from "@infrawrench/client-core";
import type { Client } from "./client";

/** `~/x` as the home directory's `x`; anything else resolved as given. */
export function expandHome(input: string): string {
  const t = input.trim();
  if (t === "~") return homedir();
  if (t.startsWith("~/") || t.startsWith("~\\")) return path.join(homedir(), t.slice(2));
  return path.resolve(t);
}

function isInfraenvName(file: string): boolean {
  const base = path.basename(file);
  return base === INFRAENV_FILE_NAME || base.endsWith(".infraenv");
}

async function kind(p: string): Promise<"file" | "dir" | null> {
  try {
    const s = await stat(p);
    return s.isFile() ? "file" : s.isDirectory() ? "dir" : null;
  } catch {
    return null;
  }
}

/**
 * The `.infraenv` a path points at: the file itself, the `.infraenv` in a
 * folder, or the one beside another file (a selected `package.json`, say).
 * Null when there is none.
 */
export async function locateInfraenv(input: string): Promise<string | null> {
  const p = expandHome(input);
  const k = await kind(p);
  if (k === "file" && isInfraenvName(p)) return p;
  const dir = k === "dir" ? p : k === "file" ? path.dirname(p) : null;
  if (dir === null) return null;
  const candidate = path.join(dir, INFRAENV_FILE_NAME);
  return (await kind(candidate)) === "file" ? candidate : null;
}

export interface InfraenvReport {
  readonly source: string;
  /** Null when the references could not be checked; `failure` says why. */
  readonly describe: InfraenvDescribeResponse | null;
  readonly failure: string | null;
}

/**
 * The file's text and, when the extension can reach Infrawrench, the describe
 * of it. Syntax is always checked offline by the caller; a describe failure
 * (no key, no network, a 403) only leaves the references unchecked.
 */
export async function loadInfraenvReport(
  file: string,
  client: () => Client,
): Promise<InfraenvReport> {
  const source = await readFile(file, "utf8");
  try {
    const c = client();
    const describe = await fetchInfraenvDescribe(c.api, c.orgId, { source });
    return { source, describe, failure: null };
  } catch (err) {
    return { source, describe: null, failure: err instanceof Error ? err.message : String(err) };
  }
}

/**
 * Write `text` with mode 0600 through a temporary file renamed over the
 * target, so a reader never sees half a file and a wider mode never survives.
 */
export async function writeSecretFile(target: string, text: string): Promise<void> {
  await mkdir(path.dirname(target), { recursive: true });
  const temporary = `${target}.${process.pid}.tmp`;
  await writeFile(temporary, text, { mode: 0o600 });
  try {
    await chmod(temporary, 0o600);
    await rename(temporary, target);
  } catch (err) {
    await rm(temporary, { force: true });
    throw err;
  }
}

async function readExisting(target: string): Promise<string | null> {
  const k = await kind(target);
  if (k === null) return null;
  if (k !== "file") throw new Error(`${target} exists and is not a file`);
  return readFile(target, "utf8");
}

export interface PullPlan {
  readonly target: string;
  /** The target exists and was not generated by Infrawrench: ask before replacing it. */
  readonly needsConfirmation: boolean;
}

/** Where a pull writes and whether it must ask first. Throws on syntax problems. */
export async function planDotenvPull(file: string, source: string): Promise<PullPlan> {
  const { document, problems } = parseInfraenv(source);
  if (problems.length > 0) {
    const first = problems[0]!;
    throw new Error(
      `${problems.length === 1 ? "A syntax problem" : `${problems.length} syntax problems`}, first at line ${first.line}: ${first.message}`,
    );
  }
  const target = path.resolve(path.dirname(file), infraenvOutputPath(document));
  if (target === path.resolve(file)) {
    throw new Error("The output setting points at the .infraenv itself");
  }
  const decision = infraenvPullDecision(await readExisting(target));
  return { target, needsConfirmation: decision === "confirm" };
}

/**
 * Resolve the file for one environment and write the `.env` where the plan
 * says. The values go straight to disk; only counts and problems come back.
 */
export async function pullDotenv(
  client: Client,
  file: string,
  source: string,
  environment: string | null,
  plan: PullPlan,
): Promise<Pick<InfraenvResolveResponse, "problems"> & { count: number }> {
  const sourceName =
    path.relative(path.dirname(plan.target), file).split(path.sep).join("/") || INFRAENV_FILE_NAME;
  const resolved = await fetchInfraenvResolve(client.api, client.orgId, {
    source,
    environment,
    sourceName,
  });
  await writeSecretFile(plan.target, resolved.dotenv);
  return { count: resolved.values.length, problems: resolved.problems };
}
