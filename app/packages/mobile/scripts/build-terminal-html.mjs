/**
 * Bundles scripts/terminal-entry.js (xterm.js + fit addon + WebView bridge)
 * into one self-contained HTML page for the mobile terminal WebView.
 *
 * Outputs (both gitignored, regenerated before dev/typecheck):
 *   assets/generated/terminal.html     — for inspection / debugging in a browser
 *   assets/generated/terminal-html.ts  — the same HTML as an exported string,
 *                                        importable by Metro/TypeScript
 */
import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptsDir = path.dirname(fileURLToPath(import.meta.url));
const pkgDir = path.dirname(scriptsDir);
const outDir = path.join(pkgDir, "assets", "generated");

async function main() {
  const result = await build({
    entryPoints: [path.join(scriptsDir, "terminal-entry.js")],
    bundle: true,
    write: false,
    outdir: "out",
    format: "iife",
    platform: "browser",
    target: ["es2019"],
    minify: true,
    logLevel: "silent",
  });

  let js = "";
  let css = "";
  for (const file of result.outputFiles) {
    if (file.path.endsWith(".js")) js = file.text;
    else if (file.path.endsWith(".css")) css = file.text;
  }
  if (!js) throw new Error("esbuild produced no JS output");
  if (!css) throw new Error("esbuild produced no CSS output (xterm.css missing?)");

  // Guard against the bundle closing our inline <script>/<style> tags early.
  const safeJs = js.replace(/<\/script/gi, "<\\/script");
  const safeCss = css.replace(/<\/style/gi, "<\\/style");

  const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover" />
<style>
html, body { height: 100%; margin: 0; padding: 0; background: #0b0d10; overflow: hidden; }
#root { height: 100%; width: 100%; }
.xterm { height: 100%; padding: 4px; box-sizing: border-box; }
${safeCss}
</style>
</head>
<body>
<div id="root" role="application" aria-label="SSH terminal"></div>
<script>${safeJs}</script>
</body>
</html>
`;

  // Escape for a TypeScript template literal: backslash, backtick, ${.
  const escaped = html.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  const ts = `// Generated by scripts/build-terminal-html.mjs — do not edit.
// Self-contained xterm.js terminal page hosted in the mobile terminal WebView.
export const terminalHtml = \`${escaped}\`;
`;

  await mkdir(outDir, { recursive: true });
  await writeFile(path.join(outDir, "terminal.html"), html, "utf8");
  await writeFile(path.join(outDir, "terminal-html.ts"), ts, "utf8");
  console.log(
    `[build-terminal-html] wrote assets/generated/terminal.html (${(html.length / 1024).toFixed(1)} KiB)`,
  );
}

main().catch((err) => {
  console.error("[build-terminal-html] failed:", err instanceof Error ? err.message : err);
  process.exit(1);
});
