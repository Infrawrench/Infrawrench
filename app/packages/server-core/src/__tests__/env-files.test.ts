import { beforeEach, describe, expect, it, vi } from "vitest";

// The readers are injected; Postgres and the plugin registry are stubbed so
// these tests are about resolution: overrides, failures kept per variable,
// each output read once, and refusals.
vi.mock("../db/client.js", () => ({ db: {} }));
vi.mock("../plugin-loader.js", () => ({
  loadPlugins: async () => [
    {
      plugin: {
        manifest: { id: "neon", displayName: "Neon" },
        resourceTypes: [
          {
            id: "branch",
            displayName: "Branch",
            outputs: [
              { key: "connectionString", label: "Connection string", sensitive: true },
              { key: "host", label: "Host", sensitive: false },
            ],
            secretExportTemplates: [
              {
                id: "t",
                label: "t",
                entries: [{ outputKey: "connectionString", envKey: "DATABASE_URL" }],
              },
            ],
          },
        ],
      },
    },
  ],
}));

const { describeInfraenv, resolveInfraenv, EnvFileRefused } =
  await import("../env-files/service.js");
type Reader = Parameters<typeof resolveInfraenv>[2] & object;

const RES = "neon:acct-1:br-1";
const row = {
  id: RES,
  pluginId: "neon",
  resourceTypeId: "branch",
  accountId: "acct-1",
  parentResourceId: null,
  displayName: "main",
  accountName: "Neon prod",
};
const secret = (name: string, value: string | null) => ({
  id: `sec-${name}`,
  name,
  encryptedValue: value === null ? null : "ct",
  encryptedValueIv: value === null ? null : "iv",
  value,
});

const SOURCE = `[env]
NODE_ENV = development
DATABASE_URL = resource("${RES}", "connectionString")
DB_HOST = resource("${RES}", "host")
STRIPE = secret("STRIPE")

[env.production]
NODE_ENV = production
EMPTY = secret("EMPTY")
`;

let reader: Reader;
let outputReads: string[];
let namedLookups: unknown[];

beforeEach(() => {
  outputReads = [];
  namedLookups = [];
  const secrets = new Map([
    ["STRIPE", secret("STRIPE", "stripe-test-value")],
    ["EMPTY", secret("EMPTY", null)],
  ]);
  reader = {
    resources: async (_org, ids) => new Map(ids.flatMap((id) => (id === RES ? [[id, row]] : []))),
    named: async (_org, match) => {
      namedLookups.push(match);
      if (match.pluginId !== "neon" || match.resourceTypeId !== "branch") return [];
      if (match.name === "main") return [row];
      if (match.name === "twin")
        return [row, { ...row, id: "neon:acct-2:br-9", accountName: "Neon EU" }];
      return [];
    },
    secrets: async (_org, names) =>
      new Map(names.flatMap((n) => (secrets.has(n) ? [[n, secrets.get(n)!]] : []))),
    resourceOutput: async (_org, r, output) => {
      outputReads.push(`${r.id}/${output}`);
      return output === "host" ? "db.example.com" : "postgres://u:p@db.example.com/app";
    },
    secretValue: async (r) => (r as ReturnType<typeof secret>).value,
  };
});

describe("resolveInfraenv", () => {
  it("resolves [env] alone without an environment", async () => {
    const out = await resolveInfraenv("org-1", { source: SOURCE }, reader);
    expect(out.environment).toBeNull();
    expect(out.values).toEqual([
      { key: "NODE_ENV", value: "development" },
      { key: "DATABASE_URL", value: "postgres://u:p@db.example.com/app" },
      { key: "DB_HOST", value: "db.example.com" },
      { key: "STRIPE", value: "stripe-test-value" },
    ]);
    expect(out.problems).toEqual([]);
    expect(out.dotenv).toMatch(/^# Auto-generated by Infrawrench\. Do not edit\./);
    expect(out.dotenv).toContain("DATABASE_URL=postgres://u:p@db.example.com/app\n");
  });

  it("lays the environment over [env] and keeps going past a variable that fails", async () => {
    const out = await resolveInfraenv(
      "org-1",
      { source: SOURCE, environment: "production", sourceName: "apps/web/.infraenv" },
      reader,
    );
    expect(out.values.map((v) => [v.key, v.value])).toContainEqual(["NODE_ENV", "production"]);
    expect(out.values.map((v) => v.key)).not.toContain("EMPTY");
    expect(out.problems).toEqual([
      { line: 9, key: "EMPTY", message: "The organization secret EMPTY has no value yet" },
    ]);
    expect(out.dotenv).toContain("# Source: apps/web/.infraenv (environment: production).");
  });

  it("reads each resource output once", async () => {
    const source = `A = resource("${RES}", "host")\nB = resource("${RES}", "host")\n`;
    const out = await resolveInfraenv("org-1", { source }, reader);
    expect(out.values).toHaveLength(2);
    expect(outputReads).toEqual([`${RES}/host`]);
  });

  it("reports a provider failure on the variable", async () => {
    reader.resourceOutput = async () => {
      throw new Error("token expired");
    };
    const out = await resolveInfraenv(
      "org-1",
      { source: `DATABASE_URL = resource("${RES}", "connectionString")\n` },
      reader,
    );
    expect(out.values).toEqual([]);
    expect(out.problems[0]!.message).toBe("Could not read connectionString of main: token expired");
  });

  it("reports a resource the organization does not have", async () => {
    const out = await resolveInfraenv(
      "org-1",
      { source: `X = resource("gone:a:b", "url")\n` },
      reader,
    );
    expect(out.problems[0]!.message).toBe("No resource gone:a:b in this organization");
  });

  it("refuses a file that does not parse, or an environment it lacks", async () => {
    await expect(resolveInfraenv("org-1", { source: "A = secret()\n" }, reader)).rejects.toThrow(
      EnvFileRefused,
    );
    await expect(
      resolveInfraenv("org-1", { source: SOURCE, environment: "staging" }, reader),
    ).rejects.toThrow("The file has no [env.staging] section; it declares production");
  });
});

describe("describeInfraenv", () => {
  it("labels references and reports dangling ones without reading values", async () => {
    const source = `${SOURCE}\n[env.staging]\nX = resource("${RES}", "nope")\nY = secret("MISSING")\n`;
    const out = await describeInfraenv("org-1", source, {}, reader);
    expect(outputReads).toEqual([]);
    expect(out.environments).toEqual(["production", "staging"]);
    expect(out.resources.find((r) => r.output === "connectionString")).toMatchObject({
      found: true,
      displayName: "main",
      pluginName: "Neon",
      resourceTypeName: "Branch",
      accountName: "Neon prod",
      outputLabel: "Connection string",
      outputKnown: true,
      sensitive: true,
    });
    expect(out.secrets).toEqual([
      { name: "STRIPE", found: true, hasValue: true },
      { name: "EMPTY", found: true, hasValue: false },
      { name: "MISSING", found: false, hasValue: false },
    ]);
    expect(out.problems.map((p) => p.message)).toEqual([
      "The organization secret EMPTY has no value yet",
      'Branch has no output "nope"',
      "No organization secret named MISSING",
    ]);
  });
});

describe("by-name references and substitutions", () => {
  const PORTABLE = `[vars]
branch = main

[env]
DATABASE_URL = resource("neon/branch", "\${branch}", "connectionString")
STRIPE = secret("\${secret}")

[vars.staging]
branch = twin

[env.staging]
`;

  it("finds a resource by name in this organization, with substitutions", async () => {
    const out = await resolveInfraenv(
      "org-1",
      { source: PORTABLE, vars: { secret: "STRIPE" } },
      reader,
    );
    expect(out.values).toEqual([
      { key: "DATABASE_URL", value: "postgres://u:p@db.example.com/app" },
      { key: "STRIPE", value: "stripe-test-value" },
    ]);
    expect(namedLookups).toEqual([{ pluginId: "neon", resourceTypeId: "branch", name: "main" }]);
  });

  it("refuses an ambiguous name and a missing substitution, per variable", async () => {
    const out = await resolveInfraenv(
      "org-1",
      { source: PORTABLE, environment: "staging" },
      reader,
    );
    expect(out.values).toEqual([]);
    expect(out.problems.map((p) => p.message)).toEqual([
      '2 resources match neon/branch named "twin": add the account, as "neon/branch@<account>", or pin one by id',
      "No value for ${secret}: set it in [vars]",
    ]);
  });

  it("describes each scope's expansion", async () => {
    const out = await describeInfraenv("org-1", PORTABLE, { vars: { secret: "STRIPE" } }, reader);
    expect(out.resources.map((r) => [r.ref, r.found, r.matches])).toEqual([
      ["name:neon/branch\u0000main\u0000connectionString", true, 1],
      ["name:neon/branch\u0000twin\u0000connectionString", false, 2],
    ]);
    expect(out.problems.map((p) => p.message)).toEqual([
      '2 resources match neon/branch named "twin": add the account, as "neon/branch@<account>", or pin one by id (environment staging)',
    ]);
  });
});
