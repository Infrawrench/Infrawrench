/**
 * Bundles each MCP view (`./views/<entry>`) into one self-contained HTML
 * page, and writes them all as `./app-views.gen.ts`. Used by
 * `scripts/generate-mcp-views.ts` and by the test that fails when the
 * committed file is stale. Never imported by the server: esbuild is a
 * build-time dependency.
 */
import { OTHER_GROUP_KEY, OTHER_SERIES_COLOR, SERIES_COLORS } from "@infrawrench/client-core";
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { MCP_VIEWS, type McpViewId } from "./app-views";

const VIEWS_DIR = fileURLToPath(new URL("./views/", import.meta.url));

async function bundle(entry: string): Promise<string> {
  const result = await build({
    entryPoints: [VIEWS_DIR + entry],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    // See `CHART` in ./views/draw.ts.
    define: {
      __IW_CHART__: JSON.stringify({
        series: SERIES_COLORS,
        other: OTHER_SERIES_COLOR,
        otherKey: OTHER_GROUP_KEY,
      }),
    },
    logLevel: "silent",
  });
  const js = result.outputFiles[0]?.text ?? "";
  // Inline in a <script>, so the text must never close it.
  return js.replace(/<\/script/gi, "<\\/script");
}

function page(js: string): string {
  return (
    '<!doctype html><html><head><meta charset="utf-8">' +
    '<meta name="viewport" content="width=device-width,initial-scale=1">' +
    `</head><body><script>${js}</script></body></html>`
  );
}

/** The text of `app-views.gen.ts`. */
export async function renderMcpViewsModule(): Promise<string> {
  const ids = Object.keys(MCP_VIEWS) as McpViewId[];
  const pages = await Promise.all(
    ids.map(async (id) => [id, page(await bundle(MCP_VIEWS[id].entry))]),
  );
  return (
    "// Generated by `pnpm --filter @infrawrench/web generate:mcp-views` from src/mcp/views/.\n" +
    "// Do not edit; app-views.test.ts fails while this is stale.\n" +
    `export const MCP_VIEW_HTML = ${JSON.stringify(Object.fromEntries(pages), null, 2)} as const;\n`
  );
}
