/**
 * Build `domain-routes.gen.ts`: every route each domain registers, and a
 * dynamic import for each domain, for the edge's lazily loaded API
 * (`api/edge.ts`). `scripts/generate-domain-routes.ts` writes it, and
 * `__tests__/domain-routes.test.ts` fails while it is stale.
 *
 * The routes are recorded from each domain's layer, not read off its
 * endpoints, because the prefix guards (`./prefix-guard.ts`) register
 * wildcard routes no endpoint describes, and those decide what an unknown
 * path under a guarded prefix answers.
 *
 * Node only (it reads `domains.ts` from disk), and it loads every domain:
 * never import it from code the API serves.
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { Effect, Layer } from "effect";
import { HttpRouter, HttpServer } from "effect/http";
import type { Domain } from "./domain";
import { DOMAINS } from "./domains";
import { ORG_TREE_GUARD, type DomainRoute, type RouteMethod } from "./domain-routes";
import { orgTreeGuard } from "./prefix-guard";
import { testMiddleware } from "./testing";

/** The routes `domain`'s layer registers, as `[method, path]`, in registration order. */
export async function recordRoutes(domain: Domain): Promise<Array<readonly [RouteMethod, string]>> {
  const recorded: Array<readonly [RouteMethod, string]> = [];
  const Recording = Layer.effect(
    HttpRouter.HttpRouter,
    Effect.map(HttpRouter.make, (router) => {
      const recording = (inner: HttpRouter.HttpRouter, prefix: string): HttpRouter.HttpRouter =>
        HttpRouter.HttpRouter.of({
          ...inner,
          prefixed: (next) => recording(inner.prefixed(next), `${prefix}${next}`),
          add: (method, path, handler, options) => {
            recorded.push([method, path === "*" ? `${prefix}/*` : `${prefix}${path}`]);
            return inner.add(method, path, handler, options);
          },
          addAll: (routes) => {
            for (const route of routes) {
              const path = route.path === "*" ? `${prefix}/*` : `${prefix}${route.path}`;
              recorded.push([route.method, path]);
            }
            return inner.addAll(routes);
          },
        });
      return recording(router, "");
    }),
  );
  await Effect.runPromise(
    Effect.scoped(
      Layer.build(
        domain.layer.pipe(
          Layer.provide(Recording),
          Layer.provide(testMiddleware()),
          Layer.provide(HttpServer.layerServices),
        ),
      ),
    ),
  );
  return recorded;
}

const DOMAINS_SOURCE = fileURLToPath(new URL("./domains.ts", import.meta.url));

/** `domains.ts`'s domain imports, as `[export name, module specifier]`. */
function domainImports(): Array<readonly [string, string]> {
  const source = readFileSync(DOMAINS_SOURCE, "utf8");
  const imports = [...source.matchAll(/^import \{ (\w+) \} from "(\.\/domains\/[\w/-]+)";$/gm)];
  return imports.map((match) => [match[1]!, match[2]!] as const);
}

/** The source of `domain-routes.gen.ts`. */
export async function renderDomainRoutesModule(): Promise<string> {
  const loaders: Array<readonly [name: string, specifier: string, exportName: string]> = [];
  for (const [exportName, specifier] of domainImports()) {
    const file = fileURLToPath(new URL(`${specifier}.ts`, import.meta.url));
    const module = (await import(file)) as Record<string, Domain | undefined>;
    const domain = module[exportName];
    if (!domain || !DOMAINS.includes(domain)) {
      throw new Error(
        `domains.ts imports ${exportName} from ${specifier}, which is not in DOMAINS`,
      );
    }
    loaders.push([domain.name, specifier, exportName]);
  }
  const loaded = new Set(loaders.map(([name]) => name));
  const missing = DOMAINS.filter((domain) => !loaded.has(domain.name)).map((d) => d.name);
  if (missing.length > 0 || loaded.size !== DOMAINS.length) {
    throw new Error(
      `every domain in DOMAINS needs its own one-line import in domains.ts (missing: ${missing.join(", ") || "duplicate names"})`,
    );
  }

  const routes: DomainRoute[] = [];
  for (const domain of [...DOMAINS, orgTreeGuard()]) {
    for (const [method, path] of await recordRoutes(domain))
      routes.push([domain.name, method, path]);
  }
  if (!routes.some(([name]) => name === ORG_TREE_GUARD)) {
    throw new Error(`orgTreeGuard no longer registers as "${ORG_TREE_GUARD}"`);
  }

  const lines = [
    "// Generated by `pnpm --filter @infrawrench/web generate:domain-routes`",
    "// (src/http/domain-routes-build.ts) from every domain's layer. Do not edit.",
    'import type { Domain } from "./domain";',
    'import type { DomainRoute } from "./domain-routes";',
    "",
    "/** Every route each domain registers (and the org tree's guard), as `[domain, method, path]`. */",
    "export const DOMAIN_ROUTES: readonly DomainRoute[] = [",
    ...routes.map((route) => `  ${JSON.stringify(route)},`),
    "];",
    "",
    "/** Each domain by name, imported on first use. */",
    "export const DOMAIN_LOADERS: Readonly<Record<string, () => Promise<Domain>>> = {",
    ...loaders.map(
      ([name, specifier, exportName]) =>
        `  ${JSON.stringify(name)}: () => import(${JSON.stringify(specifier)}).then((m) => m.${exportName}),`,
    ),
    "};",
    "",
  ];
  return lines.join("\n");
}
