#!/usr/bin/env bash
# environments/cloud-clis/lock.sh <tool>: resolve <tool>/requirements.in on the
# interpreter the tool runs on and write <tool>/requirements.lock, every
# distribution pinned with `==` and the sha256 of the one file build.sh
# installs.
#
# The resolver is pip inside env:python's own CPython (through the Wasmer
# CLI), not this machine's: pip's `--platform` changes which wheels fit but
# not how markers evaluate, and a lock made here would take a macOS or
# Linux dependency (`msal[broker]` on macOS) or miss a WASIX one. In there,
# `sys_platform` is `wasix`, wheels are `cp313`/`wasix_wasm32` from
# Wasmer's index beside PyPI or pure Python, and a project with neither
# fails to resolve, naming it, since a tool cannot build one.
#
# Run it to move a tool to a new release, then build.sh it and commit both
# files. Needs the internet (PyPI, Wasmer's index and registry) and jq.
set -euo pipefail
tool="${1:?usage: environments/cloud-clis/lock.sh <tool>}"
# shellcheck source=builtins/environments/cloud-clis/common.sh
source "$(dirname -- "${BASH_SOURCE[0]}")/common.sh"
dir="$here/environments/cloud-clis/$tool"
[[ -f "$dir/requirements.in" ]] || { echo "error: no $dir/requirements.in" >&2; exit 2; }
cp "$dir/requirements.in" "$tools_work/requirements.in"
wasix_python -m pip install --quiet --dry-run --ignore-installed --only-binary=:all: \
  --report /work/report.json -r /work/requirements.in
{
  echo "# Generated by environments/cloud-clis/lock.sh $tool from requirements.in, on python/python"
  echo "# $PYTHON_PKG_VERSION (CPython 3.13 for WASIX); do not edit."
  jq -r '.install | sort_by(.metadata.name | ascii_downcase)[]
    | "\(.metadata.name)==\(.metadata.version) \\\n    --hash=sha256:\(.download_info.archive_info.hashes.sha256)"' \
    "$tools_work/report.json"
} >"$dir/requirements.lock"
echo "wrote $dir/requirements.lock ($(grep -c '^[^# ]' "$dir/requirements.lock") distributions)"
